def format_order(order: dict | None) -> str:
    if order is None:
        return "订单数据暂不可用。"
    lines = [f"订单号：{order['order_id']}", f"状态：{order['status']}", f"下单时间：{order['created_at']}",
             f"金额：{order['total']} 元", "商品："]
    lines += [f"- {i['name']}（{i['product_id']}）× {i['quantity']}，单价 {i['price']} 元" for i in order["items"]]
    return "\n".join(lines)


